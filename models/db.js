// models/db.js
const sqlite3 = require('sqlite3');
const db = new sqlite3.Database('hospital.db');

// Enable Foreign Keys
db.get("PRAGMA foreign_keys = ON");

// New Appointment Table
const createAppointmentTable = `CREATE TABLE IF NOT EXISTS APPOINTMENT (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  DOCTOR_ID INTEGER NOT NULL,
  PATIENT_ID INTEGER NOT NULL,
  APPOINTMENT_DATE DATETIME NOT NULL,
  STATUS TEXT NOT NULL DEFAULT 'booked',
  REASON TEXT,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (DOCTOR_ID) REFERENCES USER(ID),
  FOREIGN KEY (PATIENT_ID) REFERENCES USER(ID)
)`;

// New User Table
const createUserTable = `CREATE TABLE IF NOT EXISTS USER (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  EMAIL TEXT UNIQUE NOT NULL,
  ROLE TEXT NOT NULL,
  PASSWORD TEXT NOT NULL,
  FULL_NAME TEXT NOT NULL,
  SPECIALIZATION TEXT,
  LICENSE_NUMBER TEXT,
  PHONE TEXT,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
)`;

// New Visit Table (Fixed Typo: Taple -> Table)
const createVisitTable = `CREATE TABLE IF NOT EXISTS VISIT (
 ID INTEGER PRIMARY KEY AUTOINCREMENT,
 APPOINTMENT_ID INTEGER UNIQUE NOT NULL,
 COMPLAINTS TEXT,
 DIAGNOSIS TEXT,
 PRESCRIPTION TEXT,
 FOLLOW_UP_REQUIRED INTEGER DEFAULT 0,
 CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (APPOINTMENT_ID) REFERENCES APPOINTMENT (ID)
)`;

// New AuthLog Table 
const createAuthLogTable = `CREATE TABLE IF NOT EXISTS AUTH_LOG (
 ID INTEGER PRIMARY KEY AUTOINCREMENT,
 USER_ID INTEGER,
 EMAIL_ATTEMPTED TEXT,
 SUCCESS INTEGER NOT NULL,
 IP_ADDRESS TEXT,
 CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (USER_ID) REFERENCES USER(ID)
)`;

module.exports = {
    db,
    createAppointmentTable,
    createUserTable,
    createVisitTable, // Fixed naming here
    createAuthLogTable,
};